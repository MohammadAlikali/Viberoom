private val EnglishTypography = buildTypography(PlusJakartaSansFamily)
private val RtlScriptTypography = buildTypography(VazirmatnFamily)

val VibeRoomTypography: Typography = EnglishTypography

fun vibeTypographyFor(appLanguage: AppLanguage): Typography = when (appLanguage) {
    AppLanguage.ENGLISH -> EnglishTypography
    AppLanguage.DARI_PERSIAN, AppLanguage.PASHTO -> RtlScriptTypography
}
